export class OpenBrowserError extends Error {
  constructor(code, message) {
    super(message);
    this.name = 'OpenBrowserError';
    this.code = code;
    this.nextAction = recoveryHints[code];
  }
}

const unavailable = () => new OpenBrowserError('SERVICE_UNAVAILABLE', '请先启动 open-browser 本地服务。');

export class OpenBrowserClient {
  constructor(options = {}) {
    const selected = pathsForProfile(options.profileId ?? profileId);
    this.socketPath = options.socketPath ?? selected.socketPath;
    this.tokenPath = options.tokenPath ?? process.env.OPEN_BROWSER_CLIENT_TOKEN_FILE ?? selected.tokenPath;
    this.agent = options.agent ?? new Agent({ keepAlive: true, maxSockets: 4 });
    const codex = process.env.CODEX_THREAD_ID || process.env.CODEX_SESSION_ID;
    this.agentName = options.agentName ?? (process.env.OPEN_BROWSER_AGENT_NAME?.trim() ||
      (codex ? 'Codex' : options.fallbackName ?? 'SDK'));
  }

  async call(method, params = {}) {
    if (!agentMethods.includes(method))
      throw new OpenBrowserError('UNKNOWN_METHOD', '未知的 Agent API 方法。');
    if (!params || typeof params !== 'object' || Array.isArray(params))
      throw new OpenBrowserError('INVALID_PARAMS', '参数必须是 JSON 对象。');
    if (['createWorkspace', 'open'].includes(method) &&
        (typeof params.name !== 'string' || !params.name.trim()))
      throw new OpenBrowserError('TASK_NAME_REQUIRED', '创建 Agent 任务时必须提供非空任务名称 name。');
    if (['createWorkspace','open'].includes(method) && params.agentName === undefined)
      params = { ...params, agentName: this.agentName };
    return localRequest(this.socketPath,this.tokenPath,'/v1/call',method,params,this.agent);
  }
  async capabilities() {
    try { return await this.call('capabilities'); }
    catch(error) {
      if (['UNKNOWN_METHOD','unknown_method','forbidden'].includes(error.code)) return {version:0,visual:{enabled:false,actions:[]}};
      throw error;
    }
  }
  captureVisual(page, options = {}) { return this.call('captureVisual',{...options,...page}); }
  respondDialog(page, response) { return this.call('respondDialog',{...response,...page}); }
  listUploads(workspaceId) { return this.call('listUploads',{workspaceId}); }
  listDownloads(workspaceId) { return this.call('listDownloads', {workspaceId}); }
  listOutputs(workspaceId) { return this.call('listOutputs', {workspaceId}); }
  readOutput(workspaceId, outputId, options = {}) { return this.call('readOutput', { ...options, workspaceId, outputId }); }
  cancelDownload(workspaceId, downloadId) { return this.call('cancelDownload', {workspaceId, downloadId}); }
  eventCursor(workspaceId) { return this.call('eventCursor',{workspaceId}); }
  waitForEvent(page,options) { return this.call('waitForEvent',{...options,...page}); }
  listEvents(workspaceId, options = {}) { return this.call('listEvents', { ...options, workspaceId }); }
  getRecoverySummary(workspaceId, options = {}) { return this.call('getRecoverySummary', { ...options, workspaceId }); }
  listOperations(workspaceId, options = {}) { return this.call('listOperations', { ...options, workspaceId }); }
  finishWorkspace(workspaceId, keepPageIds, operationId) {
    return this.call('finishWorkspace', {workspaceId, keepPageIds, operationId});
  }

  /** Finish a workspace with a fresh idempotency key generated by the SDK. */
  finish(workspaceId, keepPageIds = []) {
    return this.finishWorkspace(workspaceId, keepPageIds, randomUUID());
  }

  createWorkspace(params = {}) { return this.call('createWorkspace', params); }
  open(params = {}) { return this.call('open', params); }
  grantOrigin(params) { return this.call('grantOrigin', params); }
  listWorkspaces() { return this.call('listWorkspaces'); }
  getWorkspace(workspaceId) { return this.call('getWorkspace', { workspaceId }); }
  openPage(workspaceId, url) { return this.call('openPage', { workspaceId, url }); }
  observe(page) { return this.call('observe', page); }
  observeAndAct(page, request = {}) {
    const { actions, observeAfter, timeoutMs, operationId = randomUUID(), ...observeOptions } = request;
    if (!Array.isArray(actions) || actions.length === 0)
      return Promise.reject(new OpenBrowserError('INVALID_PARAMS', 'observeAndAct 需要至少一个 action。'));
    return this.call('observeAndAct', {
      ...page, ...observeOptions, actions, observeAfter, timeoutMs, operationId,
    });
  }
  /** Open one URL and immediately return its first observation. */
  async openAndObserve(options = {}, observeOptions = {}) {
    const page = await this.open(options);
    const observation = await this.observe({ ...page, ...observeOptions });
    return { ...page, observation };
  }
  /** Observe immediately before acting, while preserving document and control checks. */
  async actAfterObserve(page, request = {}) {
    return this.observeAndAct(page, request).then(({ observation, receipt }) => ({ observation, receipt }));
  }
  runWorkflow(page, request) { return this.call('runWorkflow',{...request,...page}); }
  act(page, operation) { return this.call('act', { ...operation, ...page }); }
  diagnoseOperation(workspaceId, operationId) { return this.call('diagnoseOperation', {workspaceId, operationId}); }
  getOperation(workspaceId, operationId) {
    return this.call('getOperation', { workspaceId, operationId });
  }
  cancelOperation(workspaceId, operationId) {
    return this.call('cancelOperation', { workspaceId, operationId });
  }
  handOff(workspaceId) { return this.call('handOff', { workspaceId }); }
  closeWorkspace(workspaceId) { return this.call('closeWorkspace', { workspaceId }); }
  close() { this.agent.destroy(); }
}

export async function localRequest(socket, credentials, endpoint, method, params, agent) {
    const body = JSON.stringify({ method, params });
    let token;
    try {
      token = (await readFile(credentials, 'utf8')).trim();
    } catch {
      throw unavailable();
    }
    if (!token) throw unavailable();
    return new Promise((resolve, reject) => {
      const req = request({
        socketPath: socket,
        method: 'POST',
        path: endpoint,
        headers: {
          authorization: 'Bearer ' + token,
          'content-type': 'application/json',
          'content-length': Buffer.byteLength(body),
        },
      agent,
      }, res => {
        let data = '';
        res.setEncoding('utf8');
        res.on('data', chunk => { data += chunk; });
        res.on('error', () => reject(unavailable()));
        res.on('end', () => {
          let reply;
          try { reply = JSON.parse(data); } catch {}
          if (typeof reply?.error?.code === 'string') {
            reject(new OpenBrowserError(reply.error.code, reply.error.message || reply.error.code));
          } else if (res.statusCode === 200 && reply && Object.hasOwn(reply, 'result')) {
            resolve(reply.result);
          } else {
            reject(new OpenBrowserError('INVALID_RESPONSE', '本地服务返回了无法识别的响应。'));
          }
        });
      });
      req.once('error', () => reject(unavailable()));
      req.setTimeout(limits.clientTimeoutMs, () => {
        reject(new OpenBrowserError('REQUEST_TIMEOUT', '等待服务响应超时。对于已派发的动作，请按 operationId 查询回执。'));
        req.destroy();
      });
      req.end(body);
    });
  }
